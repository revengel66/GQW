    @Transactional(transactionManager = "analyticsTransactionManager", readOnly = true)
    public SettingsView view() {
        Map<String, String> raw = loadCachedValues();
        Instant updatedAt = readLastUpdatedAt();
        List<SettingGroupView> groups = new ArrayList<>();
        for (SettingGroupDefinition group : GROUPS) {
            List<SettingView> settings = group.settings().stream()
                .map(def -> toView(def, raw.get(def.key())))
                .toList();
            groups.add(new SettingGroupView(
                group.code(),
                displayGroupTitle(group.code(), group.title()),
                displayGroupDescription(group.code(), group.description()),
                settings
            ));
        }
        return new SettingsView(updatedAt, groups);
    }

    @Transactional(transactionManager = "analyticsTransactionManager")
    public SettingsView update(Map<String, String> values, String updatedBy) {
        ensureTableExists();
        if (values == null || values.isEmpty()) {
            return view();
        }
        for (Map.Entry<String, String> entry : values.entrySet()) {
            String key = normalizeKey(entry.getKey());
            SettingDefinition definition = DEFINITIONS.get(key);
            if (definition == null) {
                continue;
            }
            String normalized = normalizeByType(definition, entry.getValue());
            upsertSetting(key, normalized, updatedBy);
        }
        invalidateCache();
        return view();
    }

    @Transactional(transactionManager = "analyticsTransactionManager", readOnly = true)
    public boolean getBoolean(String key, boolean fallback) {
        String value = resolveRawValue(key);
        if (value == null || value.isBlank()) {
            return fallback;
        }
        String normalized = value.trim().toLowerCase(Locale.ROOT);
        if (Set.of("true", "1", "yes", "on").contains(normalized)) {
            return true;
        }
        if (Set.of("false", "0", "no", "off").contains(normalized)) {
            return false;
        }
        return fallback;
    }

    @Transactional(transactionManager = "analyticsTransactionManager", readOnly = true)
    public int getInt(String key, int fallback, int min, int max) {
        String value = resolveRawValue(key);
        int parsed = fallback;
        if (value != null && !value.isBlank()) {
            try {
                parsed = Integer.parseInt(value.trim());
            } catch (NumberFormatException ignored) {
                parsed = fallback;
            }
        }
        return clamp(parsed, min, max);
    }

    @Transactional(transactionManager = "analyticsTransactionManager", readOnly = true)
    public String getText(String key, String fallback) {
        String value = resolveRawValue(key);
        if (value == null) {
            return fallback;
        }
        String normalized = value.trim();
        return normalized.isEmpty() ? fallback : normalized;
    }

    private String resolveRawValue(String key) {
        String normalizedKey = normalizeKey(key);
        if (normalizedKey == null) {
            return null;
        }
        if (!DEFINITIONS.containsKey(normalizedKey)) {
            return null;
        }
        Map<String, String> values = loadCachedValues();
        String dbValue = values.get(normalizedKey);
        return (dbValue == null || dbValue.isBlank()) ? null : dbValue;
    }

    private SettingView toView(SettingDefinition definition, String dbValue) {
        String effective = (dbValue == null || dbValue.isBlank())
            ? definition.defaultValue()
            : normalizeByType(definition, dbValue);
        return new SettingView(
            definition.key(),
            displaySettingLabel(definition.key(), definition.label()),
            displaySettingHelp(definition.key(), definition.help()),
            definition.kind().name(),
            effective,
            definition.defaultValue(),
            definition.minValue(),
            definition.maxValue(),
            definition.options(),
            dbValue != null && !dbValue.isBlank()
        );
    }

