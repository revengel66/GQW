    private boolean tableExists() {
        Integer count = jdbcTemplate.queryForObject(
            """
                select count(*)
                from INFORMATION_SCHEMA.TABLES
                where lower(TABLE_SCHEMA) = :schema
                  and lower(TABLE_NAME) = :table
            """,
            Map.of(
                "schema", DB_TABLE_SCHEMA,
                "table", DB_TABLE_NAME
            ),
            Integer.class
        );
        return count != null && count > 0;
    }

    private void ensureTableExists() {
        if (tableExists()) {
            return;
        }
        jdbcTemplate.getJdbcTemplate().execute(
            """
                create table if not exists analytics.runtime_setting (
                    setting_key varchar(128) primary key,
                    setting_value varchar(2048) not null,
                    updated_at timestamp with time zone not null default now(),
                    updated_by varchar(128)
                )
            """
        );
    }

    private static String normalizeByType(SettingDefinition definition, String raw) {
        String value = raw == null ? "" : raw.trim();
        if (value.isBlank()) {
            if (definition.kind() == SettingKind.TEXT) {
                return "";
            }
            throw new IllegalArgumentException(
                "Значение параметра \"" + definition.key() + "\" обязательно."
            );
        }
        return switch (definition.kind()) {
            case BOOLEAN -> normalizeBoolean(definition, value);
            case INTEGER -> {
                int parsed;
                try {
                    parsed = Integer.parseInt(value);
                } catch (NumberFormatException ex) {
                    throw new IllegalArgumentException(
                        "???????? ????????? \"" + displaySettingLabel(definition.key(), definition.label())
                            + "\" ?????? ???? ????? ??????."
                    );
                }
                if (definition.minValue() != null && parsed < definition.minValue()) {
                    throw new IllegalArgumentException(
                        "???????? ????????? \"" + displaySettingLabel(definition.key(), definition.label())
                            + "\" ?????? ???? ?? ?????? " + definition.minValue() + "."
                    );
                }
                if (definition.maxValue() != null && parsed > definition.maxValue()) {
                    throw new IllegalArgumentException(
                        "???????? ????????? \"" + displaySettingLabel(definition.key(), definition.label())
                            + "\" ?????? ???? ?? ?????? " + definition.maxValue() + "."
                    );
                }
                yield String.valueOf(parsed);
            }
            case ENUM -> normalizeEnum(definition, value);
            case TEXT -> value;
        };
    }

    private static String normalizeEnum(SettingDefinition definition, String value) {
        String normalized = value.trim().toUpperCase(Locale.ROOT);
        boolean allowed = definition.options().stream()
            .map(SettingOption::value)
            .anyMatch(option -> option.equalsIgnoreCase(normalized));
        if (allowed) {
            return normalized;
        }
        throw new IllegalArgumentException(
            "???????? ????????? \"" + displaySettingLabel(definition.key(), definition.label())
                + "\" ?????? ???? ????? ?? ??????????? ?????????."
        );
    }

    private static String normalizeBoolean(SettingDefinition definition, String value) {
        String normalized = value.trim().toLowerCase(Locale.ROOT);
        if (Set.of("true", "1", "yes", "on").contains(normalized)) {
            return "true";
        }
        if (Set.of("false", "0", "no", "off").contains(normalized)) {
            return "false";
        }
        throw new IllegalArgumentException(
            "???????? ????????? \"" + displaySettingLabel(definition.key(), definition.label())
                + "\" ?????? ???? true ??? false."
        );
    }

    private static int clamp(int value, Integer min, Integer max) {
        int bounded = value;
        if (min != null) {
            bounded = Math.max(min, bounded);
        }
        if (max != null) {
            bounded = Math.min(max, bounded);
        }
        return bounded;
    }

    private static String normalizeKey(String key) {
        if (key == null) {
            return null;
        }
        String normalized = key.trim();
        return normalized.isEmpty() ? null : normalized;
    }

