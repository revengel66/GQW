    private Map<String, String> loadCachedValues() {
        CacheSnapshot cached = cacheSnapshot;
        Instant now = Instant.now();
        if (cached != null && now.isBefore(cached.cachedAt().plus(CACHE_TTL))) {
            return cached.values();
        }
        Map<String, String> loaded = loadAllFromDb();
        cacheSnapshot = new CacheSnapshot(now, loaded);
        return loaded;
    }

    private Map<String, String> loadAllFromDb() {
        if (!tableExists()) {
            return Map.of();
        }
        return jdbcTemplate.query(
            "select setting_key, setting_value from " + DB_TABLE,
            rs -> {
                Map<String, String> map = new LinkedHashMap<>();
                while (rs.next()) {
                    String key = normalizeKey(rs.getString("setting_key"));
                    if (key != null) {
                        map.put(key, rs.getString("setting_value"));
                    }
                }
                return map;
            }
        );
    }

    private Instant readLastUpdatedAt() {
        if (!tableExists()) {
            return null;
        }
        List<Instant> result = jdbcTemplate.query(
            "select max(updated_at) as updated_at from " + DB_TABLE,
            (rs, rowNum) -> {
                var ts = rs.getTimestamp("updated_at");
                return ts == null ? null : ts.toInstant();
            }
        );
        if (result.isEmpty()) {
            return null;
        }
        return result.getFirst();
    }

    private void upsertSetting(String key, String value, String updatedBy) {
        MapSqlParameterSource params = new MapSqlParameterSource()
            .addValue("key", key)
            .addValue("value", value)
            .addValue("updatedBy", updatedBy);
        try {
            jdbcTemplate.update(
                """
                    insert into analytics.runtime_setting (setting_key, setting_value, updated_at, updated_by)
                    values (:key, :value, now(), :updatedBy)
                    on conflict (setting_key)
                    do update set
                        setting_value = excluded.setting_value,
                        updated_at = now(),
                        updated_by = excluded.updated_by
                """,
                params
            );
        } catch (BadSqlGrammarException ex) {
            upsertSettingPortable(key, value, updatedBy, ex);
        }
    }

    private void upsertSettingPortable(String key, String value, String updatedBy, BadSqlGrammarException original) {
        MapSqlParameterSource params = new MapSqlParameterSource()
            .addValue("key", key)
            .addValue("value", value)
            .addValue("updatedBy", updatedBy);
        try {
            int updated = jdbcTemplate.update(
                """
                    update analytics.runtime_setting
                    set setting_value = :value,
                        updated_at = now(),
                        updated_by = :updatedBy
                    where setting_key = :key
                """,
                params
            );
            if (updated == 0) {
                jdbcTemplate.update(
                    """
                        insert into analytics.runtime_setting (setting_key, setting_value, updated_at, updated_by)
                        values (:key, :value, now(), :updatedBy)
                    """,
                    params
                );
            }
        } catch (BadSqlGrammarException fallbackError) {
            throw original;
        }
    }

