    private static SettingGroupDefinition group(
        String code,
        String title,
        String description,
        SettingDefinition... settings
    ) {
        return new SettingGroupDefinition(code, title, description, List.of(settings));
    }

    private static SettingDefinition def(
        String key,
        String label,
        String help,
        SettingKind kind,
        String defaultValue
    ) {
        return new SettingDefinition(key, label, help, kind, defaultValue, null, null, List.of());
    }

    private static SettingDefinition def(
        String key,
        String label,
        String help,
        SettingKind kind,
        String defaultValue,
        Integer min,
        Integer max
    ) {
        return new SettingDefinition(key, label, help, kind, defaultValue, min, max, List.of());
    }

    private static SettingDefinition def(
        String key,
        String label,
        String help,
        SettingKind kind,
        String defaultValue,
        List<SettingOption> options
    ) {
        return new SettingDefinition(key, label, help, kind, defaultValue, null, null, options);
    }

    private static List<SettingOption> options(String... values) {
        List<SettingOption> result = new ArrayList<>();
        for (int i = 0; i + 1 < values.length; i += 2) {
            result.add(new SettingOption(values[i], values[i + 1]));
        }
        return result;
    }

    private static Map<String, SettingDefinition> buildDefinitionMap(Collection<SettingGroupDefinition> groups) {
        Map<String, SettingDefinition> map = new LinkedHashMap<>();
        for (SettingGroupDefinition group : groups) {
            for (SettingDefinition setting : group.settings()) {
                map.put(setting.key(), setting);
            }
        }
        return map;
    }

